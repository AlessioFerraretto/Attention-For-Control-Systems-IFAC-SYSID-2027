from typing import Protocol

import torch


class SSMComponent(Protocol):
    """Cosa fa l'SSM interno: penalty ausiliari"""

    def extra_loss(self, model, cfg, global_step) -> torch.Tensor: ...
    def setup(self, model, cfg, device, train_loader) -> None: ...
    def setup_for_eval(self, model) -> None: ...
    def logging_metrics(self, all_available_metrics) -> tuple[dict, str]: ...

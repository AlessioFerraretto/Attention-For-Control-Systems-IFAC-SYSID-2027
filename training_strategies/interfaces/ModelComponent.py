from typing import Protocol

from torch.optim import Optimizer

from training_strategies.interfaces import SSMComponent


class ModelComponent(Protocol):
    """Setup, ottimizzatore, clipping, scheduling — possiede un SSMComponent."""

    ssm: SSMComponent

    def setup(self, model, cfg, device, train_loader) -> None: ...
    def setup_for_eval(self, model) -> None: ...
    def make_optimizer(self, model, cfg) -> Optimizer: ...
    def clip_gradients(self, model) -> None: ...
    def before_step(self, model, global_step) -> None: ...  # scheduling tau/lambda
    def enter_eval(self, model) -> None: ...
    def exit_eval(self, model) -> None: ...
    def logging_metrics(self, model) -> tuple[dict, str]: ...
